package com.medinexus.medicore.persistence;

import static org.assertj.core.api.Assertions.assertThat;

import java.util.Optional;
import java.util.UUID;

import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.transaction.PlatformTransactionManager;
import org.springframework.transaction.support.TransactionTemplate;

import com.medinexus.medicore.persistence.entity.PersistenceCheck;
import com.medinexus.medicore.persistence.repository.IPersistenceCheckRepository;

import jakarta.persistence.EntityManager;

/**
 * Integration test that writes to and reads from the real PostgreSQL database
 * through the Spring Data JPA repository.
 *
 * <p>Requirements: the PostgreSQL container is running, the table
 * {@code persistence_check} exists ({@code infrastructure/database/create-persistence-check.sql})
 * and {@code DB_URL}, {@code DB_USERNAME} and {@code DB_PASSWORD} are set.
 * See {@code infrastructure/database/README.md}.
 *
 * <p>The test only touches the single row it inserts itself. That row is
 * deleted by its generated ID in {@link #deleteTestRecord()}, which also runs
 * when an assertion fails.
 */
@SpringBootTest
class PersistenceCheckRepositoryIntegrationTest {

    private final IPersistenceCheckRepository repository;
    private final EntityManager entityManager;
    private final TransactionTemplate transactionTemplate;

    /** ID of the row inserted by the test; {@code null} until the insert succeeded. */
    private Long insertedId;

    @Autowired
    PersistenceCheckRepositoryIntegrationTest(IPersistenceCheckRepository repository,
                                              EntityManager entityManager,
                                              PlatformTransactionManager transactionManager) {
        this.repository = repository;
        this.entityManager = entityManager;
        this.transactionTemplate = new TransactionTemplate(transactionManager);
    }

    @Test
    void savedEntityCanBeReadBackFromDatabase() {
        String description = "persistence-check-" + UUID.randomUUID();

        transactionTemplate.executeWithoutResult(status -> {
            // INSERT is sent to PostgreSQL immediately by the flush.
            PersistenceCheck saved = repository.saveAndFlush(new PersistenceCheck(description));
            insertedId = saved.getId();
            assertThat(insertedId).as("ID generated by PostgreSQL").isNotNull();

            // Detach everything so the following read cannot be served from
            // Hibernate's first-level cache and must SELECT from the database.
            entityManager.clear();
            assertThat(entityManager.contains(saved)).isFalse();

            Optional<PersistenceCheck> found = repository.findById(insertedId);

            assertThat(found).isPresent();
            assertThat(found.get()).isNotSameAs(saved);
            assertThat(found.get().getId()).isEqualTo(insertedId);
            assertThat(found.get().getDescription()).isEqualTo(description);
        });

        // The transaction above has committed. Read again in a new transaction
        // (new persistence context) to confirm the row was really stored.
        Optional<PersistenceCheck> committed = repository.findById(insertedId);
        assertThat(committed).isPresent();
        assertThat(committed.get().getDescription()).isEqualTo(description);
    }

    @AfterEach
    void deleteTestRecord() {
        if (insertedId != null) {
            // Deletes only the row created by this test. If the transaction was
            // rolled back (failed assertion inside it), the row does not exist
            // and deleteById does nothing.
            repository.deleteById(insertedId);
            assertThat(repository.existsById(insertedId)).as("test record removed").isFalse();
        }
    }
}
