CREATE TABLE messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_id BIGINT NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    recipient_id BIGINT NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    content TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT ck_messages_different_accounts CHECK (sender_id <> recipient_id),
    CONSTRAINT ck_messages_content CHECK (content ~ '[^[:space:]]' AND char_length(content) <= 5000)
);

CREATE INDEX ix_messages_recipient_created ON messages (recipient_id, created_at, id);
CREATE INDEX ix_messages_participants_created ON messages (sender_id, recipient_id, created_at, id);
