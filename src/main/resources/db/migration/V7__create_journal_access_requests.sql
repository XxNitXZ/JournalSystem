-- Journal access requests: a PATIENT account and a Patient that MediCore registered in FHIR have the same
-- personnummer. A DOCTOR approves (the account is then linked through users.fhir_patient_id) or rejects.
-- Rows are never deleted by the application: the table is the decision history. Only logical IDs are stored.
CREATE TABLE journal_access_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    fhir_patient_id VARCHAR(64) NOT NULL REFERENCES registered_patients (fhir_patient_id),
    status VARCHAR(16) NOT NULL,
    reviewed_by BIGINT REFERENCES users (id) ON DELETE SET NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    reviewed_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT ck_journal_access_requests_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    -- A decided request always has a review time; a pending one never has a reviewer or review time.
    CONSTRAINT ck_journal_access_requests_review
        CHECK ((status = 'PENDING' AND reviewed_at IS NULL AND reviewed_by IS NULL)
            OR (status <> 'PENDING' AND reviewed_at IS NOT NULL))
);

-- At most one active (pending) request per account and FHIR Patient; decided requests remain as history.
CREATE UNIQUE INDEX uq_journal_access_requests_pending
    ON journal_access_requests (user_id, fhir_patient_id) WHERE status = 'PENDING';
CREATE INDEX ix_journal_access_requests_status ON journal_access_requests (status, created_at);
CREATE INDEX ix_journal_access_requests_user ON journal_access_requests (user_id);
CREATE INDEX ix_journal_access_requests_fhir_patient ON journal_access_requests (fhir_patient_id);
