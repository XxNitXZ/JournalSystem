-- Messaging service baseline (NIT-324). Runs in schema `messaging` as user `messaging_svc`.
--
-- Same table, constraints and indexes as the Lab 1 monolith's V10. One difference: sender_id and recipient_id no
-- longer reference users, because accounts now belong to the Identity service in another schema. Both hold account
-- ids (identity.users.id). The sender comes from the caller's JWT, and the service checks the recipient's existence
-- and role with Identity before saving (docs/architecture.md, D4).
--
-- Messaging's first Flyway migration (moved here from infrastructure/database/migrations/messaging/ in NIT-335).

CREATE TABLE messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_id BIGINT NOT NULL,
    recipient_id BIGINT NOT NULL,
    content TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT ck_messages_different_accounts CHECK (sender_id <> recipient_id),
    CONSTRAINT ck_messages_content CHECK (content ~ '[^[:space:]]' AND char_length(content) <= 5000)
);

CREATE INDEX ix_messages_recipient_created ON messages (recipient_id, created_at, id);
CREATE INDEX ix_messages_participants_created ON messages (sender_id, recipient_id, created_at, id);
