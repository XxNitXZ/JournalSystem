-- Identity service baseline (NIT-324). Runs in schema `identity` as user `identity_svc`.
--
-- Same tables, columns, constraints and indexes as the Lab 1 monolith after V2–V9 (users) and V7–V8
-- (journal_access_requests). One difference: journal_access_requests.fhir_patient_id no longer references
-- registered_patients, because that table now belongs to the Clinical service in another schema. Identity checks the
-- id with Clinical before writing it (docs/architecture.md, D2).
--
-- Staged here until NIT-788 moves it to services/identity/src/main/resources/db/migration/.

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(255) NOT NULL,
    fhir_patient_id VARCHAR(255),
    fhir_practitioner_id VARCHAR(255),
    given_name VARCHAR(100),
    family_name VARCHAR(100),
    personnummer VARCHAR(12),
    phone_number VARCHAR(16),

    -- One fixed KTH FHIR server per database; references are logical ids only (from V3).
    CONSTRAINT uq_users_fhir_patient_id UNIQUE (fhir_patient_id),
    CONSTRAINT uq_users_fhir_practitioner_id UNIQUE (fhir_practitioner_id),
    CONSTRAINT ck_users_fhir_patient_id_format
        CHECK (fhir_patient_id IS NULL OR fhir_patient_id ~ '^[A-Za-z0-9.-]{1,64}$'),
    CONSTRAINT ck_users_fhir_practitioner_id_format
        CHECK (fhir_practitioner_id IS NULL OR fhir_practitioner_id ~ '^[A-Za-z0-9.-]{1,64}$'),
    CONSTRAINT ck_users_fhir_patient_role
        CHECK (fhir_patient_id IS NULL OR role = 'PATIENT'),
    CONSTRAINT ck_users_fhir_practitioner_role
        CHECK (fhir_practitioner_id IS NULL OR role IN ('DOCTOR', 'STAFF')),

    -- Display name: both or neither, never blank (from V4).
    CONSTRAINT ck_users_names_complete
        CHECK ((given_name IS NULL) = (family_name IS NULL)),
    CONSTRAINT ck_users_given_name_not_blank
        CHECK (given_name IS NULL OR btrim(given_name) <> ''),
    CONSTRAINT ck_users_family_name_not_blank
        CHECK (family_name IS NULL OR btrim(family_name) <> ''),

    -- Personnummer normalized to 12 digits, one account per personnummer (from V6).
    CONSTRAINT uq_users_personnummer UNIQUE (personnummer),
    CONSTRAINT ck_users_personnummer_format CHECK (personnummer IS NULL OR personnummer ~ '^[0-9]{12}$'),

    -- Optional phone number: optional '+' and 6–15 digits (from V9).
    CONSTRAINT ck_users_phone_number_format
        CHECK (phone_number IS NULL OR phone_number ~ '^\+?[0-9]{6,15}$')
);

-- Journal access requests: the decision history. Rows are never deleted by the application (from V7, V8).
CREATE TABLE journal_access_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    -- Logical id of a Patient in Clinical's registered_patients. No foreign key across services.
    fhir_patient_id VARCHAR(64),
    status VARCHAR(16) NOT NULL,
    reviewed_by BIGINT REFERENCES users (id) ON DELETE SET NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    reviewed_at TIMESTAMP WITH TIME ZONE,

    CONSTRAINT ck_journal_access_requests_fhir_patient_id_format
        CHECK (fhir_patient_id IS NULL OR fhir_patient_id ~ '^[A-Za-z0-9.-]{1,64}$'),
    CONSTRAINT ck_journal_access_requests_status
        CHECK (status IN ('AWAITING_RECORD', 'PENDING', 'APPROVED', 'REJECTED')),
    -- Open requests are never reviewed; decided ones always have a review time.
    CONSTRAINT ck_journal_access_requests_review
        CHECK ((status IN ('AWAITING_RECORD', 'PENDING') AND reviewed_at IS NULL AND reviewed_by IS NULL)
            OR (status IN ('APPROVED', 'REJECTED') AND reviewed_at IS NOT NULL)),
    -- Only a request awaiting its record has no FHIR Patient.
    CONSTRAINT ck_journal_access_requests_record
        CHECK ((status = 'AWAITING_RECORD' AND fhir_patient_id IS NULL)
            OR (status <> 'AWAITING_RECORD' AND fhir_patient_id IS NOT NULL))
);

-- At most one open request per account.
CREATE UNIQUE INDEX uq_journal_access_requests_open
    ON journal_access_requests (user_id) WHERE status IN ('AWAITING_RECORD', 'PENDING');
CREATE INDEX ix_journal_access_requests_status ON journal_access_requests (status, created_at);
CREATE INDEX ix_journal_access_requests_user ON journal_access_requests (user_id);
CREATE INDEX ix_journal_access_requests_fhir_patient ON journal_access_requests (fhir_patient_id);
